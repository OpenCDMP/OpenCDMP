import { ChangeDetectionStrategy, Component, computed, DestroyRef, effect, inject, input, output, signal, untracked } from '@angular/core';
import { takeUntilDestroyed } from '@angular/core/rxjs-interop';
import { FormControl, FormGroup, ReactiveFormsModule, Validators } from '@angular/forms';
import { MatButtonModule } from '@angular/material/button';
import { MatFormFieldModule } from '@angular/material/form-field';
import { MatIconModule } from '@angular/material/icon';
import { MatInputModule } from '@angular/material/input';
import { MatProgressBarModule } from '@angular/material/progress-bar';
import { MatSelectModule } from '@angular/material/select';
import { IsActive } from '@app/core/common/enum/is-active.enum';
import { DescriptionPrefillingRequest, PrefillingSearchRequest } from '@app/core/model/description-prefilling-request/description-prefilling-request';
import { DescriptionTemplate } from '@app/core/model/description-template/description-template';
import { Description } from '@app/core/model/description/description';
import { RootSection } from '@app/core/model/plan-blueprint/plan-blueprint';
import { Prefilling, PrefillingSource } from '@app/core/model/prefilling-source/prefilling-source';
import { PrefillingSourceLookup } from '@app/core/query/prefilling-source.lookup';
import { PrefillingSourceService } from '@app/core/services/prefilling-source/prefilling-source.service';
import { DescriptionEditorHelper } from '@app/ui/plan/plan-editor-blueprint/plan-description-editor/plan-description-editor-helper';
import { HttpErrorHandlingService } from '@common/modules/errors/error-handling/http-error-handling.service';
import { Guid } from '@common/types/guid';
import { TranslateModule } from '@ngx-translate/core';
import { finalize } from 'rxjs';
import { nameof } from 'ts-simple-nameof';
import { templateTypeStyle } from '../shared/template-type-style';

export interface ImportedDescription {
	/** Description generated by the backend from the external record, not yet added to the plan. */
	description: Description;
	template: DescriptionTemplate;
	source: PrefillingSource;
	record: Prefilling;
}

/**
 * "Import from a published source" step: pick the template the metadata should be mapped onto,
 * choose one of the section's prefilling sources, look a record up by identifier or title, then
 * let the backend generate a pre-filled description from it.
 */
@Component({
	selector: 'app-new-description-import',
	imports: [ReactiveFormsModule, MatButtonModule, MatFormFieldModule, MatIconModule, MatInputModule, MatProgressBarModule, MatSelectModule, TranslateModule],
	templateUrl: './new-description-import.component.html',
	styleUrl: './new-description-import.component.scss',
	changeDetection: ChangeDetectionStrategy.OnPush,
})
export class NewDescriptionImportComponent {
	private readonly prefillingSourceService = inject(PrefillingSourceService);
	private readonly httpErrorHandlingService = inject(HttpErrorHandlingService);
	private readonly destroyRef = inject(DestroyRef);

	section = input<RootSection | undefined>();
	templates = input<DescriptionTemplate[]>([]);
	/** Template groups that already reached their maximum number of assets in this section. */
	maxMultiplicityIds = input<Guid[]>([]);

	imported = output<ImportedDescription>();
	busyChange = output<boolean>();

	protected readonly form = new FormGroup({
		templateId: new FormControl<Guid | null>(null, Validators.required),
		sourceId: new FormControl<Guid | null>(null, Validators.required),
		// Not `required`: "Look up" is simply disabled while empty, so the field never shows a red error state.
		identifier: new FormControl<string>('', { nonNullable: true }),
	});

	protected readonly selectableTemplates = computed(() =>
		this.templates().filter(t => !this.maxMultiplicityIds()?.includes(t.groupId)));

	private static readonly ALL_SOURCES_PAGE_SIZE = 100;

	protected readonly sources = signal<PrefillingSource[]>([]);
	protected readonly sourcesLoading = signal(true);
	protected readonly searching = signal(false);
	protected readonly results = signal<Prefilling[] | null>(null);
	protected readonly lastTerm = signal('');
	protected readonly importingId = signal<string | null>(null);

	protected readonly typeStyle = templateTypeStyle;

	constructor() {
		// Pre-select when there is only one option, otherwise make the user choose.
		effect(() => {
			const templates = this.selectableTemplates();
			const control = this.form.controls.templateId;
			if (templates.length === 1) {
				control.setValue(templates[0].id);
			} else if (!templates.some(t => t.id === control.value)) {
				control.setValue(null);
			}
		});
		effect(() => {
			const enabled = !!this.section()?.prefillingSourcesEnabled;
			const ids = this.section()?.prefillingSources?.map(x => x.id) ?? [];
			untracked(() => this.loadSources(enabled, ids));
		});
		this.form.controls.sourceId.valueChanges.pipe(takeUntilDestroyed(this.destroyRef)).subscribe(() => this.results.set(null));
	}

	protected selectedTemplate(): DescriptionTemplate | undefined {
		const id = this.form.controls.templateId.value;
		return this.templates().find(t => t.id === id);
	}

	protected selectedSource(): PrefillingSource | undefined {
		const id = this.form.controls.sourceId.value;
		return this.sources().find(s => s.id === id);
	}

	protected canLookUp(): boolean {
		return this.form.valid && this.form.controls.identifier.value.trim().length > 0;
	}

	protected lookUp(): void {
		if (!this.canLookUp() || this.searching()) { return; }
		const term = this.form.controls.identifier.value.trim();
		const request: PrefillingSearchRequest = { like: term, prefillingSourceId: this.form.controls.sourceId.value };
		this.searching.set(true);
		this.lastTerm.set(term);
		this.prefillingSourceService.search(request)
			.pipe(takeUntilDestroyed(this.destroyRef), finalize(() => this.searching.set(false)))
			.subscribe({
				next: records => this.results.set(records ?? []),
				error: error => {
					this.results.set([]);
					this.httpErrorHandlingService.handleBackedRequestError(error);
				},
			});
	}

	protected import(record: Prefilling): void {
		const template = this.selectedTemplate();
		const source = this.selectedSource();
		if (!template || !source || this.importingId()) { return; }
		const request = {
			prefillingSourceId: source.id,
			descriptionTemplateId: template.id,
			data: { id: record.id, data: record.data },
		} as DescriptionPrefillingRequest;

		this.importingId.set(record.id);
		this.busyChange.emit(true);
		this.prefillingSourceService.generate(request, DescriptionEditorHelper.DescriptionTemplateInDescriptionLookupFields())
			.pipe(takeUntilDestroyed(this.destroyRef), finalize(() => { this.importingId.set(null); this.busyChange.emit(false); }))
			.subscribe({
				next: description => {
					if (description) { this.imported.emit({ description, template, source, record }); }
				},
				error: error => this.httpErrorHandlingService.handleBackedRequestError(error),
			});
	}

	private loadSources(enabled: boolean, ids: Guid[]): void {
		this.results.set(null);
		if (!enabled) {
			this.sources.set([]);
			this.sourcesLoading.set(false);
			return;
		}
		const lookup = new PrefillingSourceLookup();
		if (ids.length) { lookup.ids = ids; }
		lookup.isActive = [IsActive.Active];
		lookup.page = { offset: 0, size: ids.length || NewDescriptionImportComponent.ALL_SOURCES_PAGE_SIZE };
		lookup.order = { items: [nameof<PrefillingSource>(x => x.label)] };
		lookup.project = { fields: [nameof<PrefillingSource>(x => x.id), nameof<PrefillingSource>(x => x.label), nameof<PrefillingSource>(x => x.code)] };
		this.sourcesLoading.set(true);
		this.prefillingSourceService.query(lookup)
			.pipe(takeUntilDestroyed(this.destroyRef), finalize(() => this.sourcesLoading.set(false)))
			.subscribe({
				next: result => {
					const items = result?.items ?? [];
					this.sources.set(items);
					this.form.controls.sourceId.setValue(items.length === 1 ? items[0].id : null);
				},
				error: error => {
					this.sources.set([]);
					this.httpErrorHandlingService.handleBackedRequestError(error);
				},
			});
	}
}
